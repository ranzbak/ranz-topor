"""Generate / check ``docs/user/configuration.md`` from the settings schema.

    PYTHONPATH=plugin python -m topor.docs_gen --check    # exit 1 when the committed file drifted
    PYTHONPATH=plugin python -m topor.docs_gen --write    # regenerate it

Complexity: O(#settings).
"""

from __future__ import annotations

import sys
from pathlib import Path

from .config import _range_text, toml_value
from .schema import DEPRECATED, KICAD_ONLY, PAST_DEFAULTS, REMOVED, REMOVED_IN, SECTIONS, SETTINGS

REFERENCE = Path(__file__).resolve().parents[2] / "docs" / "user" / "configuration.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_reference_md(settings=SETTINGS) -> str:
    out = [
        "# Configuration reference (`topor.toml`)",
        "",
        "<!-- GENERATED by `python -m topor.docs_gen --write` from plugin/topor/schema.py; do not edit by hand. -->",
        "",
        "`topor.toml` lives next to the `.kicad_pro` file. It is created with every key and its documentation on the",
        "first run. Unknown keys give a warning; an invalid value gives a warning and the default is used.",
        "Options at their default are written as commented lines (`# key = value`), so a later version can change the",
        "default for you; a line without `# ` is your own value and is never changed by the plugin.",
        "Options added in a later version are not added to an existing file (see the known limitation at the end).",
        "Keys marked *since 0.5.0* are accepted but written commented-out until that engine feature is available.",
        "Keys that were removed (listed at the end) are ignored with the warning `CFG_REMOVED_KEY`; deprecated keys",
        "(section Deprecated keys) are ignored with the warning `CFG_DEPRECATED_KEY`, which names their line.",
        "",
    ]
    for sec, sec_doc in SECTIONS.items():
        rows = [s for s in settings if s.section == sec]
        if not rows and sec != "layers":  # [layers] also holds the per-layer roles
            continue
        out += [f"## `[{sec}]`", "", sec_doc, ""]
        if rows:
            out += ["| Key | Type | Default | Unit | Range | Description |", "|---|---|---|---|---|---|"]
        for s in rows:
            doc = s.doc
            if s.kicad_place:
                doc += f" KiCad: {s.kicad_place}."
            if s.since:
                doc += f" *Since {s.since}.*"
            out.append(f"| `{s.key}` | {s.type} | `{_cell(toml_value(s.default))}` | {s.unit} | {_cell(_range_text(s))} | {_cell(doc)} |")
        if rows:
            out.append("")
        if sec == "layers":
            out += ["Per-layer roles are written as keys in this section, e.g. `F.Cu = \"signal\"`, `In1.Cu = \"gnd\"`.",
                    "Roles: `signal`, `mixed`, `gnd`, `pwr`, `jumper`; a layer is routed iff `signal` or `mixed`.",
                    "Precedence: roles here > KiCad layer types (if any copper layer is power/mixed/jumper) > default by copper count",
                    "(2: S,S; 4: S,GND,PWR,S; 6: S,GND,PWR,S,GND,S; 8: S,GND,S,PWR,GND,S,GND,S). Other counts need roles here.", ""]
    out += ["## Set in KiCad, not in `topor.toml`", "", "| Behaviour | Where in KiCad |", "|---|---|"]
    out += [f"| {n} | {_cell(p)} |" for n, p in KICAD_ONLY]
    out += ["", "## Pinned defaults", "",
            "When a default changes, a `topor.toml` that has the old default as an active line keeps it (the plugin never",
            "edits your values) and every run warns `CFG_PINNED_OLD_DEFAULT`, one warning per option, naming the line.",
            "Delete or comment the line to follow the defaults, or let the pre-flight dialog do it (user 2026-11-17): select",
            "the finding, tick *Use the current default for <key>*, and Route comments the line out (`# ` in front) and runs",
            "with the current default (the report notes it as `CFG_DEFAULT_RESTORED`). The same checkbox is offered for a",
            "deprecated key (below). History of changed defaults:", "",
            "| Key | Old default | Changed |", "|---|---|---|"]
    out += [f"| `{s}.{k}` | `{_cell(toml_value(old))}` | {when} |" for (s, k), hist in PAST_DEFAULTS.items() for old, when in hist]
    if not PAST_DEFAULTS:
        out.append("| (none at present) | | |")
    out += ["", "## Deprecated keys", "",
            "A `topor.toml` that still sets one keeps working: the key is ignored with the warning `CFG_DEPRECATED_KEY`,",
            "which names its line, and the pre-flight dialog offers *Use the current default* to comment the line out.", "",
            "| Key | Deprecated | Why |", "|---|---|---|"]
    out += [f"| `{s}.{k}` | {when} | {_cell(why)} |" for (s, k), (when, why) in DEPRECATED.items()]
    out += ["", "Known limitation: an existing `topor.toml` never gets options that were added in a later version; they use",
            "their default until you add them (copy the commented block from a freshly generated file).",
            "", "## Removed keys", "", f"Removed in {REMOVED_IN}: the topological core never read them. A `topor.toml` that "
            "still sets one keeps working; the key is ignored with the warning `CFG_REMOVED_KEY`.", "",
            "| Key | Why |", "|---|---|"]
    out += [f"| `{s}.{k}` | {_cell(why)} |" for (s, k), why in REMOVED.items()]
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = render_reference_md(SETTINGS)
    if "--write" in args:
        REFERENCE.parent.mkdir(parents=True, exist_ok=True)
        REFERENCE.write_text(text, encoding="utf-8")
        print(f"wrote {REFERENCE}")
        return 0
    if "--check" in args:
        if not REFERENCE.exists() or REFERENCE.read_text(encoding="utf-8") != text:
            print(f"{REFERENCE} is out of date; run: PYTHONPATH=plugin python -m topor.docs_gen --write", file=sys.stderr)
            return 1
        print("configuration reference is up to date")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
