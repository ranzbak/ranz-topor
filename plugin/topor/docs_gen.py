"""Generate / check ``docs/user/configuration.md`` from the settings schema.

    PYTHONPATH=plugin python -m topor.docs_gen --check    # exit 1 when the committed file drifted
    PYTHONPATH=plugin python -m topor.docs_gen --write    # regenerate it

Complexity: O(#settings).
"""

from __future__ import annotations

import sys
from pathlib import Path

from .config import _range_text, toml_value
from .schema import KICAD_ONLY, SECTIONS, SETTINGS

REFERENCE = Path(__file__).resolve().parents[2] / "docs" / "user" / "configuration.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_reference_md(settings=SETTINGS) -> str:
    out = [
        "# Configuration reference (`topor.toml`)",
        "",
        "<!-- GENERATED by `python -m topor.docs_gen --write` from plugin/topor/schema.py; do not edit by hand. -->",
        "",
        "`topor.toml` lives next to the `.kicad_pro` file. It is created with every key and its documentation on the",
        "first run. Unknown keys give a warning; an invalid value gives a warning and the default is used.",
        "Keys marked *since 0.5.0* are accepted but written commented-out until that engine feature is available.",
        "",
    ]
    for sec, sec_doc in SECTIONS.items():
        rows = [s for s in settings if s.section == sec]
        if not rows:
            continue
        out += [f"## `[{sec}]`", "", sec_doc, "",
                "| Key | Type | Default | Unit | Range | Description |", "|---|---|---|---|---|---|"]
        for s in rows:
            doc = s.doc
            if s.kicad_place:
                doc += f" KiCad: {s.kicad_place}."
            if s.since:
                doc += f" *Since {s.since}.*"
            out.append(f"| `{s.key}` | {s.type} | `{_cell(toml_value(s.default))}` | {s.unit} | {_cell(_range_text(s))} | {_cell(doc)} |")
        out.append("")
    out += ["## Set in KiCad, not in `topor.toml`", "", "| Behaviour | Where in KiCad |", "|---|---|"]
    out += [f"| {n} | {_cell(p)} |" for n, p in KICAD_ONLY]
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = render_reference_md(SETTINGS)
    if "--write" in args:
        REFERENCE.parent.mkdir(parents=True, exist_ok=True)
        REFERENCE.write_text(text, encoding="utf-8")
        print(f"wrote {REFERENCE}")
        return 0
    if "--check" in args:
        if not REFERENCE.exists() or REFERENCE.read_text(encoding="utf-8") != text:
            print(f"{REFERENCE} is out of date; run: PYTHONPATH=plugin python -m topor.docs_gen --write", file=sys.stderr)
            return 1
        print("configuration reference is up to date")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
